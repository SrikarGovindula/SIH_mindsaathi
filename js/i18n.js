class I18nManager {
    constructor() {
        this.currentLang = localStorage.getItem('smriti_lang') || 'as';
    }

    setLanguage(langCode) {
        if (I18N_DATA[langCode]) {
            this.currentLang = langCode;
            localStorage.setItem('smriti_lang', langCode);
            document.documentElement.lang = langCode;
            this.applyTranslations();
            return true;
        }
        return false;
    }

    getLang() {
        return this.currentLang;
    }

    t(key) {
        const langDict = I18N_DATA[this.currentLang] || I18N_DATA['en'];
        return langDict[key] || I18N_DATA['en'][key] || key;
    }

    getItem(itemKey) {
        const langDict = I18N_DATA[this.currentLang] || I18N_DATA['en'];
        if (langDict.items && langDict.items[itemKey]) {
            return langDict.items[itemKey];
        }
        return I18N_DATA['en'].items[itemKey] || { name: itemKey, story: "" };
    }

    applyTranslations() {
        // Find elements with data-i18n
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = this.t(key);
            if (translation) {
                if (el.tagName === 'INPUT' && el.getAttribute('placeholder')) {
                    el.placeholder = translation;
                } else {
                    el.textContent = translation;
                }
            }
        });

        // Trigger custom event for dynamic components
        window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: this.currentLang } }));
    }
}

window.i18n = new I18nManager();
